<?php

declare(strict_types=1);

namespace Orion\NotifyRules\Filament\Pages;

use Filament\Actions\Action;
use Filament\Facades\Filament;
use Filament\Notifications\Notification;
use Filament\Pages\Page;
use Filament\Support\Icons\Heroicon;
use Illuminate\Database\Eloquent\Model;
use LogicException;
use Orion\NotifyRules\Models\TelegramLink;
use Orion\NotifyRules\Telegram\TelegramLinkManager;

final class TelegramConnection extends Page
{
    protected static bool $shouldRegisterNavigation = false;

    protected static ?string $slug = 'notify-rules/telegram';

    protected string $view = 'notify-rules::pages.telegram-connection';

    /** Deep link generated by the connect action; shown until the bot confirms the link. */
    public ?string $deepLink = null;

    public function getTitle(): string
    {
        return __('notify-rules::notify-rules.telegram.page.title');
    }

    public function getSubheading(): string
    {
        return __('notify-rules::notify-rules.telegram.page.description');
    }

    public function getLink(): ?TelegramLink
    {
        return app(TelegramLinkManager::class)->linkFor($this->user());
    }

    public function isConnected(): bool
    {
        return app(TelegramLinkManager::class)->isConnected($this->user());
    }

    public function getLinkTtl(): int
    {
        return (int) config('notify-rules.telegram.link_token_ttl', 15);
    }

    /**
     * Polled while a link is pending, so the page flips to "connected" once the user presses Start.
     */
    public function refreshStatus(): void
    {
        $link = $this->getLink();

        if ($link === null || $link->link_token === null) {
            $this->deepLink = null;
        }
    }

    public function connectAction(): Action
    {
        return Action::make('connect')
            ->label(fn (): string => $this->isConnected()
                ? __('notify-rules::notify-rules.telegram.page.actions.reconnect')
                : __('notify-rules::notify-rules.telegram.page.actions.connect'))
            ->icon(Heroicon::OutlinedPaperAirplane)
            ->color(fn (): string => $this->isConnected() ? 'gray' : 'primary')
            ->action(function (TelegramLinkManager $links): void {
                try {
                    $this->deepLink = $links->deepLink($links->createLinkToken($this->user()));
                } catch (LogicException) {
                    Notification::make()
                        ->title(__('notify-rules::notify-rules.telegram.page.notifications.not_configured'))
                        ->danger()
                        ->send();
                }
            });
    }

    public function disconnectAction(): Action
    {
        return Action::make('disconnect')
            ->label(__('notify-rules::notify-rules.telegram.page.actions.disconnect'))
            ->color('danger')
            ->requiresConfirmation()
            ->modalDescription(__('notify-rules::notify-rules.telegram.page.actions.disconnect_confirm'))
            ->visible(fn (): bool => $this->isConnected())
            ->action(function (TelegramLinkManager $links): void {
                $links->disconnect($this->user());
                $this->deepLink = null;

                Notification::make()
                    ->title(__('notify-rules::notify-rules.telegram.page.notifications.disconnected'))
                    ->success()
                    ->send();
            });
    }

    private function user(): Model
    {
        $user = Filament::auth()->user();

        if (! $user instanceof Model) {
            abort(403);
        }

        return $user;
    }
}
